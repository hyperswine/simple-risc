#!/usr/bin/env bash
# Build the Deflate timing probe through the same Gowin flow as the core, or
# sweep it: FREQ_MHZ PLL/SDC clock, DEFLATE_TARGET_MHZ over-constrained placer
# target (default 1.1x), DEFLATE_PLACE_OPTION 0-4, DEFLATE_FILLER_BANKS inert
# fill, DEFLATE_VECTOR the streamed vector. Run once for each placement.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
ide="${GOWIN_IDE:-/Applications/GowinIDE.app/Contents/Resources/Gowin_EDA/IDE}"

freq="${FREQ_MHZ:-84}"
target="${DEFLATE_TARGET_MHZ:-$((freq + freq / 10))}"
placement="${DEFLATE_PLACE_OPTION:-0}"
case "$placement" in 0|1|2|3|4) ;; *) echo "DEFLATE_PLACE_OPTION must be 0-4" >&2; exit 1;; esac
filler="${DEFLATE_FILLER_BANKS:-0}"
vector="${DEFLATE_VECTOR:-big}"
out="${DEFLATE_OUT:-$root/output/tangnano20k/deflate-f$freq-p$placement-f$filler}"
if [[ "$out" != /* ]]; then out="$PWD/$out"; fi

# PLL: 27 MHz in, PFD = 27/(IDIV+1), CLKOUT = PFD*(FBDIV+1), VCO = CLKOUT*ODIV
# in the 400-1200 MHz the working core PLLs use. IDIV_SEL 8 gives multiples of
# 3 up to 189 MHz; IDIV_SEL 2 gives multiples of 9 above that.
case "$freq" in
  *[!0-9]*) echo "FREQ_MHZ must be an integer" >&2; exit 1;;
esac
pll_python=$(python3 - "$freq" <<'PYEOF'
import sys
f = int(sys.argv[1])
for idiv in (8, 5, 2, 1, 0):
    pfd = 27 / (idiv + 1)
    fbd = f / pfd - 1
    if fbd < 0 or fbd != int(fbd) or int(fbd) > 63:
        continue
    for odiv in (16, 8, 4, 2):
        vco = f * odiv
        if 400 <= vco <= 1200:
            print(f"{int(fbd)} {idiv} {odiv}")
            raise SystemExit
raise SystemExit("no PLL configuration for this frequency")
PYEOF
)
read -r fbdiv idiv odiv <<<"$pll_python"
echo "PLL: FBDIV_SEL=$fbdiv IDIV_SEL=$idiv ODIV_SEL=$odiv (VCO $((freq * odiv)) MHz)"

if [[ "${DEFLATE_SKIP_CLASH:-0}" != 1 ]]; then
  cd "$root"
  cabal run -v0 clash -- -isrc -hide-package simple-risc src/Deflate.hs --verilog \
    -fclash-clear -outputdir output/tangnano20k/deflate-generated
  cd "$here"
fi
rtl="$root/output/tangnano20k/deflate-generated/Deflate.topEntity/deflate_inflate.v"
[[ -f "$rtl" ]] || { echo "missing generated RTL: $rtl" >&2; exit 1; }

mkdir -p "$out"
python3 - "$here" "$out" "$vector" "$filler" "$fbdiv" "$idiv" "$odiv" <<'PYEOF'
from pathlib import Path
import sys
here, out, vector, filler, fbdiv, idiv, odiv = sys.argv[1:8]
vectors = Path(here) / "vectors"
hexlines = (vectors / f"{vector}.deflate.hex").read_text().split()
words = [int(b, 16) for b in hexlines if b]
if not 1 <= len(words) <= 65535:
    raise SystemExit("ROM probe requires 1..65535 input bytes; the decoder itself supports longer streams")
rom = Path(out) / "vector_rom.v"
rom.write_text(
    "`default_nettype wire\n// generated by build_deflate.sh from vectors/%s.deflate.hex\n" % vector
    + "module vector_rom(input clk, input [15:0] addr, output reg [7:0] dout);\n"
    + "  reg [7:0] rom [0:%d-1];\n" % len(words)
    + "  integer i;\n"
    + "  initial begin\n"
    + "".join("    rom[%d] = 8'h%02x;\n" % (i, b) for i, b in enumerate(words))
    + "  end\n"
    + "  always @(posedge clk) dout <= rom[addr];\nendmodule\n")

wrapper = (Path(here) / "deflate_fpga.v").read_text()
wrapper = (wrapper
           .replace("DEF_PLL #(.FBDIV_SEL(DEF_FBDIV), .IDIV_SEL(DEF_IDIV), .ODIV_SEL(DEF_ODIV))",
                    "deflate_pll #(.FBDIV_SEL(%s), .IDIV_SEL(%s), .ODIV_SEL(%s))" % (fbdiv, idiv, odiv))
           .replace("parameter FILLER_BANKS = 0, parameter ROM_LEN = 4",
                    "parameter FILLER_BANKS = %s, parameter ROM_LEN = %d" % (filler, len(words))))
(Path(out) / "deflate_top.v").write_text(wrapper)

# PLL module: the proven sdram_pll shape with the divider parameters opened up.
pll = (Path(here).parent / "sdram" / "pll.v").read_text()
pll = pll.replace("module sdram_pll #(parameter FBDIV_SEL=17, ODIV_SEL=16)",
                  "module deflate_pll #(parameter FBDIV_SEL=17, parameter IDIV_SEL=8, ODIV_SEL=16)")
pll = pll.replace(".IDIV_SEL(8),    // divide by 9 -> 3 MHz PFD",
                  ".IDIV_SEL(IDIV_SEL),")
(Path(out) / "pll.v").write_text("`default_nettype wire\n" + pll)
Path(out, "pins.cst").write_text(
    'IO_LOC "clk_27m" 4;\nIO_PORT "clk_27m" IO_TYPE=LVCMOS33 PULL_MODE=UP;\n'
    'IO_LOC "btn_s1" 88;\nIO_PORT "btn_s1" IO_TYPE=LVCMOS33 PULL_MODE=DOWN;\n'
    'IO_LOC "uart_tx" 69;\nIO_PORT "uart_tx" IO_TYPE=LVCMOS33 PULL_MODE=UP DRIVE=8;\n')
print("vector %s: %d stream bytes" % (vector, len(words)))
PYEOF

cat > "$out/clocks.sdc" <<SDC
create_clock -name clk_27m -period 37.037037 [get_ports {clk_27m}]
create_generated_clock -name clk_core -source [get_ports {clk_27m}] -multiply_by $((fbdiv + 1)) -divide_by $((idiv + 1)) [get_pins {pll/pll_s2/CLKOUT}]
SDC

cat > "$out/build.tcl" <<TCL
set_device -name GW2AR-18C GW2AR-LV18QN88C8/I7
set_option -top_module top
set_option -output_base_name deflate_test
set_option -opt_goal timing
set_option -looplimit 40000
set_option -place_option $placement
set_option -frequency $target
set_option -global_freq $target
set_option -map_option 3
set_option -route_option 1
set_option -route_maxfan 8
set_option -num_critical_paths 100
set_option -gen_verilog_sim_netlist 1
add_file "$out/deflate_top.v"
add_file "$rtl"
add_file "$out/vector_rom.v"
add_file "$out/pll.v"
add_file "$out/pins.cst"
add_file "$out/clocks.sdc"
file delete -force "$out/impl/pnr/deflate_test.tr"
run all
exit
TCL

if [[ "${DEFLATE_PREPARE_ONLY:-0}" == 1 ]]; then exit 0; fi

export DYLD_LIBRARY_PATH="$ide/lib"
export DYLD_FRAMEWORK_PATH="$ide/lib"
cd "$out"
for attempt in 1 2 3; do
  if "$ide/bin/gw_sh" "$out/build.tcl" > "$out/gw_sh.log" 2>&1; then
    break
  fi
  if ! grep -q "License verification failed" "$out/gw_sh.log"; then
    tail -25 "$out/gw_sh.log" >&2; exit 1
  fi
  echo "gw_sh attempt $attempt failed licence verification; retrying"
  sleep 5
  [[ "$attempt" == 3 ]] && { tail -20 "$out/gw_sh.log" >&2; exit 1; }
done

python3 - "$out" "$freq" "$placement" "$filler" <<'PYEOF'
from pathlib import Path
import re, sys
out = Path(sys.argv[1])
timing = (out / "impl" / "pnr" / "deflate_test.tr").read_text()
util = (out / "impl" / "pnr" / "deflate_test.rpt.txt").read_text()
clock = re.search(r'^\s*\d+\s+clk_core\s+([\d.]+)\(MHz\)\s+([\d.]+)\(MHz\)', timing, re.M)
paths = re.search(r'3\.1\.1 Setup Paths Table\s*<Report Command>:(.*?)3\.1\.2 Hold Paths Table', timing, re.S)
slack = re.search(r'^\s*1\s+(-?[\d.]+)\s', paths[1], re.M) if paths else None
setup = re.search(r'<Numbers of Setup Violated Endpoints>:(\d+)', timing)
hold = re.search(r'<Numbers of Hold Violated Endpoints>:(\d+)', timing)
assert all((clock, slack, setup, hold)), "incomplete timing report"
assert abs(float(clock[1])-float(sys.argv[2])) < 0.001, "wrong clock constraint"
def res(label):
    m = re.search(r'^\s*' + label + r'\s*\|\s*([\d,]+)/(\d+)\s*\|\s*(\d+)%', util, re.M)
    return f"{m[1]}/{m[2]} ({m[3]}%)" if m else "n/a"
print(f"freq {sys.argv[2]} MHz place {sys.argv[3]} filler {sys.argv[4]}: "
      f"fmax {clock[2] if clock else '?'} MHz, worst slack {slack[1] if slack else '?'}, "
      f"setup violations {setup[1] if setup else '?'}, hold {hold[1] if hold else '?'}, "
      f"logic {res('Logic')}, registers {res('Register')}, CLS {res('CLS')}, BSRAM {res('BSRAM')}")
PYEOF
