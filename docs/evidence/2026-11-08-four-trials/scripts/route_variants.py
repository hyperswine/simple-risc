import subprocess,os,pathlib,time,json,sys
root=pathlib.Path.cwd();base=root/'output/refactor-four-2026-11-08'
variant=sys.argv[1]; modes=sys.argv[2:] or ['floorplan-p3','floorplan-p0','none-p3','wider-p3']
results=[]
for mode in modes:
    physical=base/(variant+'-physical'); source=base/(variant+'-'+mode+'-source');source.mkdir(exist_ok=True)
    # pnr_only needs the same netlist location but independently chosen CST.
    impl=source/'impl'
    if not impl.exists():impl.symlink_to(physical/'impl',target_is_directory=True)
    for f in ('clocks.sdc','build.tcl'):(source/f).write_bytes((physical/f).read_bytes())
    pins=(physical/'pins.cst').read_text()
    if mode.startswith('none') or mode.startswith('wider'):
        pins='\n'.join(x for x in pins.splitlines() if not x.startswith(('GROUP ','GRP_LOC ','// Generated by floorplan_cst.py')))+'\n'
    if mode.startswith('wider'):
        cst=source/'wider.cst'
        subprocess.run(['python3','boards/tangnano20k/sdram/floorplan_cst.py',str(base/'wider.plan'),str(physical/'impl/gwsynthesis/sdram_test.vg'),'--layout',str(physical/'layout.json'),'-o',str(cst)],check=True)
        pins+=cst.read_text()
    (source/'pins.cst').write_text(pins)
    out=base/(variant+'-'+mode);env=os.environ.copy();place=mode[-1]
    env.update(PNR_PLACE_OPTION=place,PNR_POSP='1',PNR_REPORT_PATHS='3000',PNR_TIMEOUT='1200')
    start=time.monotonic()
    with (base/(variant+'-'+mode+'.log')).open('w') as log:
        r=subprocess.run(['bash','boards/tangnano20k/sdram/pnr_only.sh',str(source),str(out)],env=env,stdout=log,stderr=subprocess.STDOUT)
    results.append(dict(variant=variant,mode=mode,returncode=r.returncode,elapsed_seconds=time.monotonic()-start))
    (base/(variant+'-'+modes[0]+'-results.json')).write_text(json.dumps(results,indent=2))
    print(results[-1],flush=True)
